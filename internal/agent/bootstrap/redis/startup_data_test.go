func syntheticRDB(body []byte) []byte {
	data := append([]byte("REDIS0012"), body...)
	table := crc64.MakeTable(0x95ac9329ac4bc9b5)
	var checksum uint64
	for _, b := range data {
		checksum = table[byte(checksum)^b] ^ (checksum >> 8)
	}
	return binary.LittleEndian.AppendUint64(data, checksum)
}

func TestStartupDataGuard(t *testing.T) {
	for _, tc := range []struct {
		name  string
		data  []byte
		empty bool
		valid bool
	}{
		{"empty RDB", syntheticRDB([]byte{0xfa, 1, 'a', 1, 'b', 0xfe, 0, 0xfb, 0, 0, 0xff}), true, true},
		{"data-holding RDB", syntheticRDB([]byte{0xfe, 0, 0xfb, 1, 0, 0xff}), false, true},
		{"unknown record", syntheticRDB([]byte{0xf7, 0xff}), false, false},
		{"corrupt checksum", append([]byte("REDIS0012\xff"), make([]byte, 8)...), false, false},
		{"truncated RDB", []byte("REDIS0012"), false, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			require.NoError(t, os.WriteFile(filepath.Join(dir, "dump.rdb"), tc.data, 0o600))
			empty, err := localDatasetEmpty(dir)
			require.Equal(t, tc.empty, empty)
			require.Equal(t, tc.valid, err == nil)
		})
	}
	dir := t.TempDir()
	empty, err := localDatasetEmpty(dir)
	require.NoError(t, err)
	require.True(t, empty)
	require.NoError(t, os.Mkdir(filepath.Join(dir, "appendonlydir"), 0o700))
	empty, err = localDatasetEmpty(dir)
	require.NoError(t, err)
	require.False(t, empty)
}

func TestIndependentRedis84RDBFixtures(t *testing.T) {
	// Generated by Redis 8.4.0 SAVE with no keys, then one synthetic key in
	// database 2. These footer checksums were emitted by Redis, not this parser.
	for _, tc := range []struct {
		name, hex string
		empty     bool
	}{
		{"empty", "524544495330303132fa0972656469732d76657205382e342e30fa0a72656469732d62697473c040fa056374696d65c2b857d26afa08757365642d6d656dc2d0cb0a00fa08616f662d62617365c000ffae38a1e39be5f2ae", true},
		{"database2", "524544495330303132fa0972656469732d76657205382e342e30fa0a72656469732d62697473c040fa056374696d65c2b857d26afa08757365642d6d656dc290f70b00fa08616f662d62617365c000fe02fb0100001173796e7468657469632d7264622d6b65791373796e7468657469632d7264622d76616c7565ff5aa7166a7b3979bb", false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			data, err := hex.DecodeString(tc.hex)
			require.NoError(t, err)
			dir := t.TempDir()
			require.NoError(t, os.WriteFile(filepath.Join(dir, "dump.rdb"), data, 0o600))
			empty, err := localDatasetEmpty(dir)
			require.NoError(t, err)
			require.Equal(t, tc.empty, empty)
		})
	}
}

func TestOnlyProvablyEmptyMultipartAOFPermitsEmptySource(t *testing.T) {
	dir := t.TempDir()
	aof := filepath.Join(dir, "appendonlydir")
	require.NoError(t, os.Mkdir(aof, 0o700))
	data, err := hex.DecodeString("524544495330303132fa0972656469732d76657205382e342e30fa0a72656469732d62697473c040fa056374696d65c2b857d26afa08757365642d6d656dc2d0cb0a00fa08616f662d62617365c000ffae38a1e39be5f2ae")
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(filepath.Join(aof, "appendonly.aof.1.base.rdb"), data, 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(aof, "appendonly.aof.1.incr.aof"), nil, 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(aof, "appendonly.aof.manifest"), []byte("file appendonly.aof.1.base.rdb seq 1 type b\nfile appendonly.aof.1.incr.aof seq 1 type i startoffset 14 endoffset 6683\n"), 0o600))
	empty, err := localDatasetEmpty(dir)
	require.NoError(t, err)
	require.True(t, empty)
	require.NoError(t, os.WriteFile(filepath.Join(aof, "appendonly.aof.1.incr.aof"), []byte("*2\r\n$6\r\nSELECT\r\n$1\r\n0\r\n"), 0o600))
	empty, err = localDatasetEmpty(dir)
	require.NoError(t, err)
	require.True(t, empty, "database selection alone does not add keys")
	require.NoError(t, os.WriteFile(filepath.Join(aof, "appendonly.aof.1.incr.aof"), []byte("synthetic-uncertain-data"), 0o600))
	empty, err = localDatasetEmpty(dir)
	require.NoError(t, err)
	require.False(t, empty)
}
